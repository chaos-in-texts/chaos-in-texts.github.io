#!/usr/bin/env python3
"""
Convert the composition-surface grids in static/data/*.npy into
static/js/surface-data.js, which the page loads directly.

Why a JS file instead of fetching .npy in the browser?
  • works when index.html is opened straight from disk (file://)
  • no fetch / CORS / npy-parsing code needed on the page

Expected .npy layout (one file per <dataset>_<model>):
  shape (N, N), float, z[i][j] = NDCG@10 at
      fused ratio = i / (N-1)   (rows)
      text  ratio = j / (N-1)   (columns)
      image ratio = 1 - text - fused
  cells with i + j > N-1 lie outside the simplex and are NaN.

Usage (from the repo root):
    python tools/npy_to_js.py
Re-run it whenever you replace or add .npy files.
"""
import glob
import json
import os
import re

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "static", "data")
OUT = os.path.join(ROOT, "static", "js", "surface-data.js")

# filename prefix -> benchmark name shown in the page
DATASETS = {"cqa": "ChartQA", "sqa": "SlideVQA"}
# filename model tag -> model key used by the page
MODELS = {
    "Jina-CLIP-v2": "Jina-CLIP-v2",
    "Trident-JinaClip": "Trident-JinaCLIP",
    "qwen3vl2b": "Qwen3-VL-E-2B",
    "Trident_qwen3vl": "Trident-Qwen3VL-2B",
    # add e.g. "qwen3vl8b": "Qwen3-VL-E-8B" here if you export more grids
}
# Fig. 1(a) of the paper is the fused = 0 edge of this grid
V_CURVE_SOURCE = ("SlideVQA", "Qwen3-VL-E-2B")


def to_list(a):
    return [[None if np.isnan(v) else round(float(v), 4) for v in row] for row in a]


def main():
    settings = {}
    for path in sorted(glob.glob(os.path.join(DATA_DIR, "*_Z.npy"))):
        name = os.path.basename(path)
        m = re.match(r"([a-z]+)_(.+)_Z\.npy$", name)
        if not m or m.group(1) not in DATASETS or m.group(2) not in MODELS:
            print(f"  skip {name} (unknown dataset/model tag — add it to the maps above)")
            continue
        z = np.load(path, allow_pickle=False).astype(float)
        if z.ndim != 2 or z.shape[0] != z.shape[1]:
            raise SystemExit(f"{name}: expected a square 2-D grid, got {z.shape}")
        n = z.shape[0]
        axis = [round(k / (n - 1), 4) for k in range(n)]
        key = f"{MODELS[m.group(2)]}|{DATASETS[m.group(1)]}"
        settings[key] = {"text": axis, "fused": axis, "z": to_list(z)}
        print(f"  {name:32s} -> {key:30s} {z.shape}  range {np.nanmin(z):.3f}–{np.nanmax(z):.3f}")

    vkey = f"{V_CURVE_SOURCE[1]}|{V_CURVE_SOURCE[0]}"
    v_curve = None
    if vkey in settings:
        g = settings[vkey]
        v_curve = {"source": vkey + " (fused ratio = 0)", "x": g["text"], "y": g["z"][0]}

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by tools/npy_to_js.py from static/data/*.npy — do not edit by hand.\n")
        f.write(" * SURFACES.settings[\"<model>|<benchmark>\"].z[i][j] = NDCG@10 at fused=fused[i], text=text[j]\n")
        f.write(" * (null outside the simplex text + fused > 1).  V_CURVE = fused=0 edge of the SlideVQA / Qwen3-VL-E-2B grid (Fig. 1a). */\n")
        f.write("window.SURFACES = " + json.dumps({"settings": settings}, separators=(",", ":")) + ";\n")
        if v_curve:
            f.write("window.V_CURVE = " + json.dumps(v_curve, separators=(",", ":")) + ";\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({os.path.getsize(OUT) / 1024:.1f} KB, {len(settings)} surfaces)")


if __name__ == "__main__":
    main()
